"""Код с базовыми математическими операциями, 
работа с граничными случаями (0, NaN, inf и т.д не проверялась)"""

def multiply(a,b):
    """УМНОЖЕНИЕ ДВУХ ЧИСЕЛ"""
    return a*b
def add(a,b):
    """Сложение двух чисел"""
    return a+b
def subtract(a,b):
    """Вычитание двух чисел"""
    return a-b
def divide(a,b):
    """Деление двух чисел"""
    return a/b